// Incommensurate (single-k) magnetic structure as a P1 superspace magCIF.
//
// Superspace group P1.1'(abg)0s: the identity and, as centring, time reversal
// combined with a half-period shift of x4 (every magnetic modulation has this
// symmetry). All atoms of the cell are listed; each magnetic atom carries its
// own Fourier components, so no symmetry is used or claimed.
//
// magCIF modulation: M(x4) = Mcos cos(2 pi x4) + Msin sin(2 pi x4),
// x4 = k.r with r the atom position (cell translation included), components
// along unit vectors parallel to a, b, c (mu_B).
// PLANE-TAS: M(r) = M1 cos(2 pi k.r - phi) + M2 sin(2 pi k.r - phi), hence
//   Mcos = M1 cos(phi) - M2 sin(phi),  Msin = M1 sin(phi) + M2 cos(phi).
const wrap=v=>{const w=Number(v)-Math.floor(Number(v));return w>1-1e-9?0:w;};
const num=v=>{const x=Number(v);if(!Number.isFinite(x))return '0';const r=Number(x.toPrecision(10));return String(Object.is(r,-0)?0:r);};
const clean=v=>Math.abs(v)<1e-12?0:v;

export function incommensurateFourierComponents(m1,m2,phaseDeg){
  const p=(Number(phaseDeg)||0)*Math.PI/180, c=Math.cos(p), s=Math.sin(p);
  return {cos:[0,1,2].map(i=>clean((Number(m1[i])||0)*c-(Number(m2[i])||0)*s)),
    sin:[0,1,2].map(i=>clean((Number(m1[i])||0)*s+(Number(m2[i])||0)*c))};
}

export function exportIncommensurateP1Mcif({lattice,atoms,q,settingFor,title='generated_magnetic_structure'}){
  if(!Array.isArray(q) || q.length!==3 || !q.every(Number.isFinite)) throw Error('Invalid propagation vector.');
  if(q.every(v=>Math.abs(v)<1e-12)) throw Error('Incommensurate: k = 0 has no modulation; use the Collinear type.');
  const labelCounts=new Map();
  const sites=(atoms||[]).map(atom=>{
    const element=String(atom.element||'X');
    const n=(labelCounts.get(element)||0)+1;
    labelCounts.set(element,n);
    const s=settingFor(atom);
    const fourier=s?.enabled ? incommensurateFourierComponents(s.m1||[0,0,0],s.m2||[0,0,0],s.phase) : null;
    const magnetic=!!fourier && [...fourier.cos,...fourier.sin].some(v=>Math.abs(v)>1e-12);
    return {label:`${element}${n}`,element,fract:[atom.x,atom.y,atom.z].map(wrap),
      occupancy:Number(atom.occupancy??1),Biso:Number(atom.Biso)||0,fourier:magnetic?fourier:null};
  });
  const magnetic=sites.filter(s=>s.fourier);
  if(!magnetic.length) throw Error('Enable at least one magnetic site with a nonzero M1 or M2 to generate an mCIF.');
  const lines=['#\\#CIF_2.0',`data_${String(title).replace(/\s+/g,'_')}`,
    '# Incommensurate magnetic structure generated by PLANE-TAS from user-entered M1, M2 and phases.',
    '# Superspace group P1.1\'(abg)0s: every atom of the cell is listed with its own Fourier components.',
    `_cell_length_a ${num(lattice.a)}`,`_cell_length_b ${num(lattice.b)}`,`_cell_length_c ${num(lattice.c)}`,
    `_cell_angle_alpha ${num(lattice.alpha)}`,`_cell_angle_beta ${num(lattice.beta)}`,`_cell_angle_gamma ${num(lattice.gamma)}`,
    '_cell_modulation_dimension 1','',
    'loop_','_cell_wave_vector_seq_id','_cell_wave_vector_x','_cell_wave_vector_y','_cell_wave_vector_z',
    `1 ${q.map(num).join(' ')}`,'',
    '_space_group_magn_ssg.name "P1.1\'(abg)0s"','',
    'loop_','_space_group_symop_magn_ssg_operation.id','_space_group_symop_magn_ssg_operation.algebraic','1 x1,x2,x3,x4,+1','',
    'loop_','_space_group_symop_magn_ssg_centering.id','_space_group_symop_magn_ssg_centering.algebraic',
    '1 x1,x2,x3,x4,+1','2 x1,x2,x3,x4+1/2,-1','',
    'loop_','_atom_site_label','_atom_site_type_symbol','_atom_site_fract_x','_atom_site_fract_y','_atom_site_fract_z',
    '_atom_site_occupancy','_atom_site_B_iso_or_equiv',
    ...sites.map(s=>`${s.label} ${s.element} ${s.fract.map(num).join(' ')} ${num(s.occupancy)} ${num(s.Biso)}`),'',
    'loop_','_atom_site_Fourier_wave_vector.seq_id','_atom_site_Fourier_wave_vector.q1_coeff','1 1','',
    'loop_','_atom_site_moment_Fourier.atom_site_label','_atom_site_moment_Fourier.axis','_atom_site_moment_Fourier.wave_vector_seq_id',
    '_atom_site_moment_Fourier_param.cos','_atom_site_moment_Fourier_param.sin',
    ...magnetic.flatMap(s=>['x','y','z'].map((axis,i)=>`${s.label} ${axis} 1 ${num(s.fourier.cos[i])} ${num(s.fourier.sin[i])}`)),''];
  return {text:lines.join('\n'),atomCount:sites.length,magneticCount:magnetic.length};
}
